/** Effective text: the admin override when set, else the built-in default. */
export function effectivePrompt(override: string | undefined, fallback: string): string {
  return override?.trim() ? override : fallback;
}

export function fillPlaceholders(
  template: string,
  values: Record<string, string>,
): string {
  return Object.entries(values).reduce(
    (text, [token, value]) => text.replaceAll(`{${token}}`, value),
    template,
  );
}
